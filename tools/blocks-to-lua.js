// Turns the lessons' solutions made with blocks (docs/lessons/*/solutions/**/blocks/*.json, as
// MINE's block editor saves them) into the Lua the editor makes from them, next to each file:
// the GameTests run that Lua through the lessons' missions. The block programs lessons give
// students (data/mine/mine_lesson_files/<lesson>/<language>/<name>.json) get their Lua in the
// GameTests' resources (mine_lesson_blocks/<lesson>/<language>/<name>.lua), out of the lessons' data.
//
//   node tools/blocks-to-lua.js           writes the .lua files
//   node tools/blocks-to-lua.js --check   fails if one is missing or out of date (CI)
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const web = path.join(root, 'src/main/resources/web');
const Blockly = require(path.join(web, 'blockly/blockly_compressed.js'));
require(path.join(web, 'blockly/blocks_compressed.js'));
const lua = require(path.join(web, 'blockly/lua_compressed.js'));
Blockly.setLocale(require(path.join(web, 'blockly/msg/en.js')));
// Some blocks (e.g. "create text with") load their shape through a bit of XML: just enough of it.
class XmlElement {
	constructor(name) {
		this.nodeName = this.tagName = name;
		this.attributes = {};
		this.childNodes = [];
	}
	setAttribute(name, value) {
		this.attributes[name] = String(value);
	}
	getAttribute(name) {
		return name in this.attributes ? this.attributes[name] : null;
	}
	appendChild(child) {
		this.childNodes.push(child);
		return child;
	}
}
Blockly.utils.xml.injectDependencies({document: {
	createElementNS: (namespace, name) => new XmlElement(name),
	createTextNode: text => ({nodeName: '#text', data: text})
}, DOMParser: class {}, XMLSerializer: class {}});

// The editor's own blocks: its script, without a page around it.
global.Blockly = Blockly;
global.window = {lua: lua};
global.location = {search: ''};
global.document = {getElementById: () => ({}), documentElement: {}, head: {appendChild() {}}, createElement: () => ({})};
global.fetch = () => Promise.reject(new Error('no server here'));
eval(fs.readFileSync(path.join(web, 'editor/editor.js'), 'utf8') + '\ndefineBlocks();');

function solutions(dir) {
	return fs.readdirSync(dir, {withFileTypes: true}).flatMap(entry => {
		const file = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			return solutions(file);
		}
		return entry.name.endsWith('.json') && path.basename(dir) === 'blocks' ? [file] : [];
	});
}

const lessonFiles = path.join(root, 'src/main/resources/data/mine/mine_lesson_files');
const lessonBlocks = path.join(root, 'src/gametest/resources/mine_lesson_blocks');
const given = fs.readdirSync(lessonFiles, {recursive: true})
	.filter(file => file.endsWith('.json'))
	.map(file => [path.join(lessonFiles, file), path.join(lessonBlocks, file.replace(/\.json$/, '.lua'))]);

const check = process.argv.includes('--check');
let stale = 0;
for (const [file, target] of solutions(path.join(root, 'docs/lessons'))
	.map(file => [file, file.replace(/\.json$/, '.lua')]).concat(given)) {
	const workspace = new Blockly.Workspace();
	Blockly.serialization.workspaces.load(JSON.parse(fs.readFileSync(file, 'utf8')), workspace);
	const name = path.basename(file);
	const code = '-- Made with blocks: ' + name + ' (open it in MINE\'s block editor).\n'
		+ '-- Generated by tools/blocks-to-lua.js: change the blocks, not this file.\n'
		+ lua.luaGenerator.workspaceToCode(workspace);
	const old = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
	if (old !== code) {
		stale++;
		if (check) {
			console.error('Out of date: ' + path.relative(root, target));
		} else {
			fs.mkdirSync(path.dirname(target), {recursive: true});
			fs.writeFileSync(target, code);
			console.log('Written: ' + path.relative(root, target));
		}
	}
	workspace.dispose();
}
if (check && stale > 0) {
	console.error('Run: node tools/blocks-to-lua.js');
	process.exit(1);
}
